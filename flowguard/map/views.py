def _architecture(data: dict, graph: dict[str, set[str]]):
    """Only cheap cycle/layer rules; share full debt normalization with lint."""
    findings, by_component = structural_findings(data, graph), defaultdict(list)
    for finding in findings:
        members = finding.message.split(";", 1)[0].split(" <-> ") if finding.code == "dependency_cycle" else [finding.component]
        for cid in members:
            by_component[cid].append(finding)
    findings, used = apply_accepted_debts(findings, normalized_debts(data))
    return findings, used, by_component


def _facet_lines(facets, indent: str) -> list[str]:
    rules = ("; " if facets.rules_source == "map" else ", ").join(facets.rules) or "built at run time"
    if facets.rules_source == "TESTED_BY":
        rules += " (from TESTED_BY)"
    bad = ", ".join(facets.known_bad) or ("built at run time" if facets.known_bad_count is None else "-")
    if facets.known_bad_source == "system-root":
        bad = str(facets.known_bad_count)
    if facets.known_bad_source in {"system", "system-root"}:
        bad += " (generated by the system model)"
    return [indent + label + ": " + text for label, text in (
        ("purpose", facets.purpose), ("rules", rules), ("known-bad", bad),
        ("code", "; ".join(facets.code) or "-"), ("tests", "; ".join(facets.tests) or "-"))]


def _count(value):
    return "?" if value is None else str(value)


def _model_lines(tree, ids: set[str], facets, *, component: str | None = None, bindings: bool = False,
                 changes=None, previous=None) -> list[str]:
    roots = sorted((tree.nodes[mid] for mid in ids if tree.nodes[mid].parent_kind != "model"
                    or tree.nodes[mid].parent not in ids), key=lambda n: n.id)
    pending, lines = [(node, 1) for node in reversed(roots)], []
    while pending:
        node, depth = pending.pop()
        fact = facets[node.id]
        purpose = fact.purpose[:50] + ("…" if len(fact.purpose) > 50 else "")
        home = f" (home {node.home})" if component and (node.home_kind != "component" or node.home != component) else ""
        mark = changes.get(("model", node.id), "") if changes is not None else ""
        prefix = mark + " " if mark else ""
        lines.append("  " * depth + prefix + f"model {node.id}: {purpose} "
                     f"({_count(fact.rule_count)} rules, {_count(fact.known_bad_count)} known-bad, {fact.test_count} tests){home}")
        before = previous.get(("model", node.id)) if previous is not None else None
        if mark == "-":
            lines[-1] += " (removed by the target)"
        elif changes is not None and bindings:
            lines.extend(_facet_lines_with_was(fact, before[1] if before else None, "  " * (depth + 1)))
        elif bindings:
            lines.extend(_facet_lines(fact, "  " * (depth + 1)))
        elif changes is not None and mark:
            delta = _node_delta("model", before, (node, fact))
            if delta:
                lines.append("  " * (depth + 1) + "changes: " + "; ".join(delta))
        pending.extend((child, depth + 1) for child in reversed(tree.children(node.id, "model")) if child.id in ids)
    return lines


def _facet_lines_with_was(fact, before, indent):
    lines, old = [], _facet_lines(before, "") if before is not None else []
    for index, line in enumerate(_facet_lines(fact, "")):
        lines.append(indent + line)
        if old and line != old[index]:
            lines.append(indent + "was: " + old[index].partition(": ")[2])
    return lines


def _node_fields(kind, record):
    node, fact = record
    fields = {"purpose": (fact.purpose,), "rules": fact.rules or ("built at run time",),
              "known-bad": fact.known_bad or (("built at run time",) if fact.known_bad_count is None else ()),
              "code": tuple(value for value in fact.code if value != "STALE"), "tests": fact.tests}
    if kind == "component":
        fields["code"] = tuple(value for value in fields["code"]
                               if not value.startswith(("entry: ", "state: ", "effects: "))) + tuple(node.get("entrypoints", []))
        fields["state"] = tuple(node.get("state", []))
        fields["effects"] = tuple(node.get("side_effects", []))
        for field, label in (("files", "files"), ("depends_on", "uses"), ("tests", "tests"), ("layer", "layer")):
            value = node.get(field, []) if field != "layer" else (node.get(field) or "unlayered",)
            fields[label] = tuple(dict.fromkeys((*fields.get(label, ()), *value)))
    elif kind == "model":
        fields["parent"] = ("system" if node.parent_kind == "system" else f"{node.parent_kind} {node.parent}",)
        fields["file"] = (node.path,)
    return fields


def _node_delta(kind, before, after):
    old = _node_fields(kind, before) if before else {}
    new = _node_fields(kind, after) if after else {}
    parts = []
    for label in dict.fromkeys([*new, *old]):
        for sign, values, other in (("+", new.get(label, ()), old.get(label, ())),
                                    ("-", old.get(label, ()), new.get(label, ()))):
            for value in values:
                if value not in other:
                    shown_label, shown_value = label, value
                    if label == "code" and value.startswith("state: "):
                        shown_label, shown_value = "state", value[7:]
                    parts.append(f"{shown_label} {sign} {shown_value}")
    return parts


def _read_facts(root, data, inv, tree, *, raw=None, source_cache=None, view=None):
    """One discovery graph per view; indexes retain the actual inventory scope."""
    if raw is None:
        raw = discover_inventory(root, inv, write_cache=view is None, data=data)
    cache = source_cache if source_cache is not None else {}
    functions = _test_function_index(root, inv, source_cache=cache)
    coverage = coverage_facts(root, data, inv, tree, raw, source_cache=cache)
    return raw, functions, coverage


def _dependency_symbols(data, inv, cid, dep, raw):
    components = {component["id"]: component for component in data["components"]}
    sources = set(component_files(components[cid], inv))
    destinations = set(component_files(components[dep], inv))
    symbols = {target.partition("#")[2] for source, targets in raw["edges"].items()
               if source.partition("#")[0] in sources for target in targets
               if target.partition("#")[0] in destinations}
    modules = {info.module: path for path, info in inv.py.items()}
    for path in sources:
        if path not in inv.py:
            continue
        for imported in inv.py[path].imports:
            module, separator, name = imported.partition(":")
            if separator and name != "*" and resolve_import(imported, modules) in destinations:
                symbols.add(name)
    return sorted(symbols)


def _dependency_lines(data, inv, cid, graph, raw):
    lines = []
    for dep in sorted(graph.get(cid, ())):
        symbols = _dependency_symbols(data, inv, cid, dep, raw)
        shown = ", ".join(symbols[:6]) if symbols else "(module import only)"
        if len(symbols) > 6:
            shown += f" (+{len(symbols) - 6} more)"
        lines.append(f"  uses {dep}: {shown}")
    return lines


def _target_comparison(root, data, inv, target):
    view = build_target_view(root, data, target)
    # A target can turn an exact source into a test, or the reverse. Keep facts
    # for both real source sets, while each snapshot retains its own test scope.
    source_paths = set()
    for mapping in (data, view.data):
        owner_index(mapping, inv)
        source_paths.update(path for component in mapping["components"]
                            for path in component_files(component, inv) if path in inv.py)
    raw = discover_inventory(root, inv, write_cache=False, data=view.data, extra_sources=source_paths)
    source_cache = {}

    def snapshot(mapping, selected_view=None):
        tree = build_tree(root, mapping, inv, view=selected_view)
        graph = component_graph(mapping, inv)
        _, functions, coverage = _read_facts(root, mapping, inv, tree, raw=raw,
                                            source_cache=source_cache, view=selected_view)
        records = {("component", c["id"]): (c, component_facets(root, mapping, inv, c, tree, graph, functions,
                                                               coverage=coverage[c["id"]]))
                   for c in mapping["components"]}
        records.update({("model", mid): (node, model_facets(root, node, view=selected_view))
                        for mid, node in tree.nodes.items()})
        return tree, graph, records, system_facets(mapping, inv, tree, graph, functions, coverage=coverage)

    old_tree, _, old, old_system = snapshot(data)
    tree, graph, new, new_system = snapshot(view.data, view)
    changes = {key: "+" if key not in old else "-" if key not in new else "~"
               for key in old.keys() | new.keys()
               if key not in old or key not in new or _node_delta(key[0], old[key], new[key])}
    old_flows = {f["id"]: f for f in data.get("flows", [])}
    new_flows = {f["id"]: f for f in view.data.get("flows", [])}
    changes.update({("flow", fid): "+" if fid not in old_flows else "-" if fid not in new_flows else "~"
                    for fid in old_flows.keys() | new_flows.keys()
                    if old_flows.get(fid) != new_flows.get(fid)})
    # Draft presence is visible even when all five facets still match today.
    # Added/removed identities still come from the actual two trees, not filenames.
    for entries in target_node_changes(root, data, target).values():
        for entry in entries:
            kind, identity = entry.split(":", 1)
            key = (kind, identity)
            if key in old and key in new or kind == "flow" and identity in old_flows and identity in new_flows:
                changes.setdefault(key, "~")
    return view, old_tree, tree, old, new, changes, graph, old_system, new_system, raw


def _show_header(data, graph, *, architecture=None, debts=None):
    if architecture is None:
        architecture, debts, _ = _architecture(data, graph)
    head = f"# {data.get('project', '')}: system, {len(data['components'])} components"
    head += ", layers (top > bottom) " + " > ".join(data["layers"]) if data.get("layers") else ", layers: none"
    return head + f"; architecture: {sum(f.level == 'error' for f in architecture)} error(s), {len(debts)} accepted debt(s)"


def _render_target_show(root, data, inv, target, *, component, detail, budget):
    view, old_tree, tree, old, new, changes, graph, old_system, new_system, raw = _target_comparison(root, data, inv, target)
    merged = view.data
    component_ids = {cid for kind, cid in old.keys() | new.keys() if kind == "component"}
    if component and component != "system":
        component_ids = {cid for cid in component_ids if cid == component or cid.startswith(component + ".")}
        if not component_ids:
            return f"no component {component!r}; run 'python -m flowguard read' to list components"[:budget]
    elif component == "system":
        component_ids = set()
    counts = {mark: sum(value == mark for value in changes.values()) for mark in "+~-"}
    lines = [_show_header(merged, graph),
             f'target: "{target.goal}" (+{counts["+"]} ~{counts["~"]} -{counts["-"]} nodes)']
    lines.append(next(line for line in new_system.code if line.startswith("coverage:")))
    if not component:
        flows = {f["id"]: f for f in [*data.get("flows", []), *merged.get("flows", [])]}
        for kind, fid in sorted(changes):
            if kind == "flow":
                flow = flows[fid]
                lines.append(f'> {changes[(kind, fid)]} flow {fid}: {flow.get("summary", "")} :: '
                             + " -> ".join(flow.get("steps", []))
                             + (f" model: {flow['model']}" if flow.get("model") else " (no model)")
                             + (" (removed by the target)" if changes[(kind, fid)] == "-" else ""))
    essential = "\n".join(lines)
    model_data = {mid: record[1] for (kind, mid), record in new.items() if kind == "model"}
    old_model_data = {mid: record[1] for (kind, mid), record in old.items() if kind == "model"}
    roots = {mid for mid, node in tree.nodes.items() if node.home_kind == "system" and ("model", mid) in changes}
    top = essential
    if component is None or component == "system":
        if component == "system":
            top += "\n" + "\n".join(_facet_lines_with_was(new_system, old_system, "  "))
        top += "\n" + "\n".join(_model_lines(tree, roots, model_data, bindings=bool(component or detail), changes=changes, previous=old))
        removed_roots = {mid for mid, node in old_tree.nodes.items() if node.home_kind == "system" and changes.get(("model", mid)) == "-"}
        top += "\n" + "\n".join(_model_lines(old_tree, removed_roots, old_model_data, changes=changes, previous=old))
    blocks = []
    for cid in sorted(component_ids):
        key = ("component", cid)
        before, after = old.get(key), new.get(key)
        ids = {mid for mid, node in tree.nodes.items() if node.home_kind == "component" and node.home == cid and ("model", mid) in changes}
        removed = {mid for mid, node in old_tree.nodes.items() if node.home_kind == "component" and node.home == cid and changes.get(("model", mid)) == "-"}
        if not component and key not in changes and not ids and not removed:
            continue
        record = after or before
        comp, fact = record
        mark = changes.get(key, "")
        heading = f"\n## {mark + ' ' if mark else ''}{cid} [{comp.get('layer') or '-'}] {fact.code[0]}, {fact.rule_count} rules"
        if mark == "-":
            removed_lines = _model_lines(old_tree, removed, old_model_data, changes=changes, previous=old)
            blocks.append((cid, "\n".join([heading + " (removed by the target)", *removed_lines])))
            continue
        body = [heading]
        if component or detail:
            body.extend(_facet_lines_with_was(fact, before[1] if before else None, "  "))
            ids = {node.id for node in tree.models_for_component(cid)}
        else:
            body.append("  " + fact.purpose[:90] + ("…" if len(fact.purpose) > 90 else ""))
            delta = _node_delta("component", before, after)
            if delta:
                body.append("  changes: " + "; ".join(delta))
        if component or detail:
            body.extend(_dependency_lines(merged, inv, cid, graph, raw))
        body.extend(_model_lines(tree, ids, model_data, component=cid if component or detail else None,
                                 bindings=bool(component or detail), changes=changes, previous=old))
        body.extend(_model_lines(old_tree, removed, old_model_data, changes=changes, previous=old))
        blocks.append((cid, "\n".join(body)))
    if component is None:
        unchanged = sum(("component", c["id"]) not in changes for c in data["components"])
        blocks.append(("unchanged", f"unchanged: {unchanged} component(s); python -m flowguard read shows them"))
    return _bounded_show(top, essential, blocks, budget)


def render_show(root: Path, data: dict, inv: Inventory, *, component: str | None, detail: bool, budget: int, target=None) -> str:
    budget = max(0, budget)
    if target is not None:
        return _render_target_show(root, data, inv, target, component=component, detail=detail, budget=budget)
    graph = component_graph(data, inv)
    tree = build_tree(root, data, inv)
    model_data = {mid: model_facets(root, node) for mid, node in tree.nodes.items()}
    raw, functions, coverage = _read_facts(root, data, inv, tree)
    component_data = {c["id"]: component_facets(root, data, inv, c, tree, graph, functions,
                                               coverage=coverage[c["id"]]) for c in data["components"]}
    comps = data["components"]
    if component == "system":
        comps = []
    elif component:
        comps = [c for c in comps if c["id"] == component or c["id"].startswith(component + ".")]
        if not comps:
            return f"no component {component!r}; run 'python -m flowguard read' to list components"[:budget]
    architecture, debts, problems = _architecture(data, graph)
    head = _show_header(data, graph, architecture=architecture, debts=debts)
    model_ids = {node.path: node.id for node in tree.nodes.values()}
    flows = [] if component else [
        f"> flow {flow['id']}: {flow.get('summary', '')} :: " + " -> ".join(flow.get("steps", []))
        + (f" model: {model_ids.get(flow['model'], flow['model'])}" if flow.get("model") else " (no model)")
        for flow in data.get("flows", [])]
    target_lines = []
    try:
        target = load_target(root)
        if target is not None:
            if validate_target(root, data, target):
                raise ValueError("invalid target")
            changes = target_node_changes(root, data, target)
            target_lines.append(f'target: "{target.goal}": +{len(changes["+"])} ~{len(changes["~"])} '
                                f'-{len(changes["-"])} nodes; see python -m flowguard read --target; '
                                'python -m flowguard target check lists what is left')
    except (OSError, ValueError, TypeError, SyntaxError, MapError):
        target_lines.append("target: .flowguard/target/map.json is invalid; run python -m flowguard target check")
    essential = "\n".join([head, *target_lines, coverage_line(coverage, summary=True), *flows])
    root_models = [] if component else _model_lines(tree, {n.id for n in tree.nodes.values() if n.home_kind == "system"},
                                                   model_data, bindings=detail)
    if component == "system":
        root_models = _facet_lines(system_facets(data, inv, tree, graph, functions, coverage=coverage), "  ")
    top = "\n".join([essential, *root_models])
    blocks: list[tuple[str, str]] = []
    for c in comps:
        files = component_files(c, inv)
        flag = "STALE" if is_stale(root, c, inv) else c["status"]
        tag = "" if flag == "confirmed" else f" [{flag}]"
        fact = component_data[c["id"]]
        lines = [f"\n## {c['id']} [{c.get('layer') or '-'}] {len(files)} files/{sum(inv.loc.get(f, 0) for f in files)} loc, {fact.rule_count} rules{tag}"]
        if component or detail:
            lines.extend(_facet_lines(fact, "  "))
        else:
            lines.append("  " + fact.purpose[:90] + ("…" if len(fact.purpose) > 90 else ""))
            if c.get("state"):
                lines.append("  state: " + "; ".join(c["state"]))
        if graph.get(c["id"]):
            if component or detail:
                lines.extend(_dependency_lines(data, inv, c["id"], graph, raw))
            else:
                lines.append("  uses: " + ", ".join(sorted(graph[c["id"]])))
        declared_only = sorted(set(c.get("depends_on", [])) - graph.get(c["id"], set()))
        if declared_only and (component or detail):
            lines.append("  declared, unverified: " + ", ".join(declared_only))
        if component or detail:
            users = sorted(k for k, v in graph.items() if c["id"] in v)
            if users:
                lines.append("  used by: " + ", ".join(users))
        if problems.get(c["id"]):
            lines.append("  problems: " + "; ".join(
                ("cycle" if f.code == "dependency_cycle" else f.code) + (" (debt)" if f.level == "info" else "")
                + ": " + f.message.partition(" (accepted debt:")[0] for f in problems[c["id"]]))
        models = {n.id for n in tree.models_for_component(c["id"])} if component or detail else {
            n.id for n in tree.nodes.values() if n.home_kind == "component" and n.home == c["id"]}
        lines.extend(_model_lines(tree, models, model_data, component=c["id"] if component or detail else None,
                                  bindings=bool(component or detail)))
        blocks.append((c["id"], "\n".join(lines)))
    return _bounded_show(top, essential, blocks, budget)


def _bounded_show(top, essential, blocks, budget):
    text = top + "\n" + "\n".join(b for _, b in blocks)
    if len(text) <= budget:
        return text
    reserve = min(160, max(len("\n... truncated"), budget - len(essential)))
    shown = ""
    for line in top.splitlines():
        candidate = shown + ("\n" if shown else "") + line
        if len(candidate) > budget - reserve:
            break
        shown = candidate
    hidden: list[str] = []
    for cid, block in blocks:
        if not hidden and len(shown) + 1 + len(block) <= budget - reserve:
            shown += "\n" + block
        else:
            hidden.append(cid)
    named = []
    for cid in hidden:
        if len(", ".join(named + [cid])) > reserve - 90:
            break
        named.append(cid)
    names = ", ".join(named) + (f" +{len(hidden) - len(named)} more" if len(named) < len(hidden) else "")
    notice = f"\n... truncated at {budget} chars; not shown: {names}; use read --component ID"
    if len(shown) + len(notice) > budget:
        notice = f"\ntruncated; not shown: {len(hidden)}"
    return (shown + notice)[:budget]


def render_mermaid(root: Path, data: dict, inv: Inventory, *, component: str | None = None, target=None) -> str:
    """Export containment, declared dependencies and ordered flows without execution."""
    current_data = data
    changes, old, new = {}, {}, {}
    if target is not None:
        view, old_tree, tree, old, new, changes, graph, _, _, raw = _target_comparison(root, data, inv, target)
        data = view.data
        all_comps = [*data["components"], *[record[0] for key, record in old.items()
                                         if key[0] == "component" and changes.get(key) == "-"]]
    else:
        all_comps = data["components"]
    flow_records = {flow["id"]: flow for flow in data.get("flows", [])}
    if target is not None:
        flow_records.update({flow["id"]: flow for flow in current_data.get("flows", [])
                             if changes.get(("flow", flow["id"])) == "-"})
    flows = sorted(flow_records.values(), key=lambda flow: flow["id"])
    visible = {c["id"] for c in all_comps} if component is None else {component}
    if component is not None:
        flows = [flow for flow in flows if any(step.partition(":")[0] == component for step in flow.get("steps", []))]
        selected = next((c for c in all_comps if c["id"] == component), None)
        if selected is None:
            return f"no component {component!r}; run 'python -m flowguard read' to list components"
        visible.update(selected.get("depends_on", []))
        visible.update(step.partition(":")[0] for flow in flows for step in flow.get("steps", []))
    comps = [c for c in all_comps if c["id"] in visible]
    if component and not comps:
        return f"no component {component!r}; run 'python -m flowguard read' to list components"
    if target is None:
        tree = build_tree(root, data, inv)
        model_data = {mid: model_facets(root, node) for mid, node in tree.nodes.items()}
        graph = component_graph(data, inv)
        raw, functions, coverage = _read_facts(root, data, inv, tree)
        component_data = {c["id"]: component_facets(root, data, inv, c, tree, graph, functions,
                                                   coverage=coverage[c["id"]]) for c in comps}
    else:
        records = {**old, **new}
        model_data = {mid: record[1] for (kind, mid), record in records.items() if kind == "model"}
        component_data = {c["id"]: records[("component", c["id"])][1] for c in comps}
    _, _, problems = _architecture(data, graph)
    homes = {c["id"] for c in comps}
    all_models = list(tree.nodes.values())
    if target is not None:
        all_models.extend(record[0] for key, record in old.items() if key[0] == "model" and changes.get(key) == "-")
    active_model_paths = {node.path: node.id for node in tree.nodes.values()}
    old_model_paths = {node.path: node.id for node in old_tree.nodes.values()} if target is not None else {}

    def flow_model_id(flow):
        paths = old_model_paths if changes.get(("flow", flow["id"])) == "-" else active_model_paths
        return paths.get(flow.get("model"), flow.get("model"))

    required_models = {flow_model_id(flow) for flow in flows if flow.get("model")}
    models = [node for node in all_models if node.id in required_models or
              (node.home_kind == "component" and node.home in homes) or
              (component is None and node.home_kind == "system")]
    used = set()

    def identifier(prefix, name):
        base = prefix + re.sub(r"[^A-Za-z0-9_]", "_", name)
        candidate, number = base, 1
        while candidate in used:
            number += 1
            candidate = f"{base}_{number}"
        used.add(candidate)
        return candidate

    def label(text):
        return str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "'").replace("\r", "").replace("\n", "<br/>")

    components = {c["id"]: identifier("c_", c["id"]) for c in comps}
    model_ids = {node.id: identifier("m_", node.id) for node in sorted(models, key=lambda n: n.id)}
    flow_ids = {flow["id"]: identifier("f_", flow["id"]) for flow in flows}
    count = sum(("component", c["id"]) in new for c in comps) if target is not None else len(comps)
    lines = ["flowchart TD", f'  root_system["{label(data.get("project", ""))}: {count} components"]']
    declared_layers = data.get("layers", []) if component is None else []
    groups = list(dict.fromkeys([*declared_layers, *[c.get("layer", "") for c in comps]]))
    for index, layer in enumerate(groups):
        members = [c for c in comps if c.get("layer", "") == layer]
        lines.append(f'  subgraph l_{index}["{label(layer or "unlayered")}"]')
        for comp in members:
            codes = sorted({("cycle" if f.code == "dependency_cycle" else f.code)
                            + (" (debt)" if f.level == "info" else "") for f in problems.get(comp["id"], [])})
            title = label(comp["id"]) + f"<br/>{component_data[comp['id']].rule_count} rules" + ("<br/>" + ", ".join(codes) if codes else "")
            lines.append(f'    {components[comp["id"]]}["{title}"]')
        lines.append("  end")
    for node in sorted(models, key=lambda n: n.id):
        fact = model_data[node.id]
        lines.append(f'  {model_ids[node.id]}(["model {label(node.id)}<br/>{_count(fact.rule_count)} rules, '
                     f'{_count(fact.known_bad_count)} known-bad"])')
    for flow in flows:
        mid = flow_model_id(flow)
        status = f"model {mid}" if flow.get("model") else "no model"
        lines.append(f'  {flow_ids[flow["id"]]}["flow {label(flow["id"])}<br/>{label(status)}"]')
    lines.extend(f"  root_system --> {components[c['id']]}" for c in comps)
    for node in sorted(models, key=lambda n: n.id):
        if node.parent_kind == "model" and node.parent in model_ids:
            parent = model_ids[node.parent]
        elif node.parent_kind == "component" and node.parent in components:
            parent = components[node.parent]
        else:
            parent = "root_system"
        lines.append(f"  {parent} --> {model_ids[node.id]}")
    for comp in comps:
        for dep in sorted(comp.get("depends_on", [])):
            if dep in components:
                lines.append(f"  {components[comp['id']]} -.-> {components[dep]}")
    for flow in flows:
        identity = flow_ids[flow["id"]]
        for number, step in enumerate(flow.get("steps", []), 1):
            cid = step.partition(":")[0]
            if cid in components:
                lines.append(f'  {identity} -->|"{number}"| {components[cid]}')
        mid = flow_model_id(flow)
        if mid in model_ids:
            lines.append(f"  {identity} --> {model_ids[mid]}")
    if target is not None:
        lines.extend(["  classDef added fill:#e6ffed,stroke:#22863a", "  classDef changed fill:#fff5b1,stroke:#b08800",
                      "  classDef removed fill:#ffeef0,stroke:#cb2431,stroke-dasharray:5 5"])
        for kind, identities in (("component", components), ("model", model_ids), ("flow", flow_ids)):
            for name, identity in identities.items():
                style = {"+": "added", "~": "changed", "-": "removed"}.get(changes.get((kind, name)))
                if style:
                    lines.append(f"  class {identity} {style}")
    return "\n".join(lines)


def _find_words(words: set[str]) -> set[str]:
    """Owner lookup also matches the singular of a plural word ("orders" ~ "order")."""
    return words | {w[:-1] for w in words if len(w) > 3 and w.endswith("s")}


def defined_symbols(component: dict, inv: Inventory, words: list[str]) -> list[tuple[str, str]]:
    """Exact raw-name matches, including the final name of a class member."""
    raw = {word.lower() for word in words}
    return sorted((symbol, path) for path in component_files(component, inv) if path in inv.py
                  for symbol in inv.py[path].symbols
                  if symbol.lower() in raw or symbol.rsplit(".", 1)[-1].lower() in raw)


def find_owners(data: dict, inv: Inventory, words: list[str], limit: int = 5) -> list[tuple[int, str, list[str]]]:
    """Rank components by how well they already own the described responsibility."""
    query = _find_words(tokens(" ".join(words)))
    scored = []
    for c in data["components"]:
        text = _find_words(tokens(" ".join([c["id"], c.get("summary", "")] + c.get("responsibilities", [])
                                           + c.get("state", []) + c.get("side_effects", []))))
        symbol_words = _find_words({w.lower() for f in component_files(c, inv) if f in inv.py
                                    for s in inv.py[f].symbols
                                    for w in re.findall(r"[A-Z]+(?![a-z])|[A-Z]?[a-z0-9]+", s)})
        score = 3 * len(query & text) + len(query & symbol_words)
        if defined_symbols(c, inv, words):
            score += 4 * len(query) + 1  # greater than every possible pure word-bag score
        if score:
            scored.append((score, c["id"], [r for r in c.get("responsibilities", []) if _find_words(tokens(r)) & query]))
    scored.sort(key=lambda x: (-x[0], -sum(len(_find_words(tokens(r)) & query) for r in x[2]), x[1]))
    return scored[:limit]


def _signature(node: ast.AST) -> str:
    a = node.args
    names = [x.arg for x in a.posonlyargs + a.args if x.arg not in ("self", "cls")]
    names += [f"*{a.vararg.arg}"] if a.vararg else []
    names += [x.arg for x in a.kwonlyargs] + ([f"**{a.kwarg.arg}"] if a.kwarg else [])
    return f"{node.name}({', '.join(names)})"


def _doc(node: ast.AST) -> str:
    doc = ast.get_docstring(node)
    return f"  # {doc.strip().splitlines()[0][:120]}" if doc else ""


def file_outline(root: Path, path: str) -> list[str]:
    """Public API outline of a Python file: docstrings and signatures, never bodies."""
    try:
        tree = ast.parse(read_source(root / path))
    except (OSError, SyntaxError) as exc:
        return [f"  (unparseable: {exc})"]
    lines = [f"  doc:{_doc(tree)[3:]}"] if _doc(tree) else []
    def module_nodes(nodes):
        for item in nodes:
            yield item
            if isinstance(item, ast.If):
                yield from module_nodes(item.body + item.orelse)
            elif isinstance(item, (ast.Try, ast.TryStar)):
                yield from module_nodes(item.body + item.orelse + item.finalbody)
                for handler in item.handlers:
                    yield from module_nodes(handler.body)

    def target_names(target):
        if isinstance(target, ast.Name):
            return [target.id] if not target.id.startswith("_") else []
        if isinstance(target, (ast.Tuple, ast.List)):
            return [name for item in target.elts for name in target_names(item)]
        return []

    assignments = []
    for node in module_nodes(tree.body):
        if isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            names = [name for target in targets for name in target_names(target)]
            if names:
                value = ast.unparse(node.value) if node.value is not None else "<annotation>"
                assignments.append(f"{', '.join(names)} = {value[:32]}" + ("..." if len(value) > 32 else ""))
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            lines.append(f"  def {_signature(node)}{_doc(node)}")
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            lines.append(f"  class {node.name}{_doc(node)}")
            lines += [f"    .{_signature(s)}" for s in node.body
                      if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef))
                      and (not s.name.startswith("_") or s.name == "__init__")]
    if assignments:
        joined = "; ".join(assignments)
        lines.insert(0, "  vars: " + joined[:110] + ("..." if len(joined) > 110 else ""))
    return lines


def render_digest(root: Path, data: dict, inv: Inventory, ids: list[str], max_lines: int) -> str:
    by_id = {c["id"]: c for c in data["components"]}
    wanted = list(by_id) if ids == ["all"] else ids
    unknown = [i for i in wanted if i not in by_id]
    if unknown:
        return f"unknown component(s) {unknown}"
    owner, _ = owner_index(data, inv)
    users_of: dict[str, set[str]] = defaultdict(set)
    for src, dsts in inv.file_deps.items():
        if src in owner:
            for dst in dsts:
                users_of[dst].add(owner[src])
    out = []
    for cid in wanted:
        files = component_files(by_id[cid], inv)
        out.append(f"# digest {cid}: {len(files)} files")
        for f in files:
            users = sorted(users_of.get(f, set()) - {cid})
            out.append(f"{f} ({inv.loc.get(f, 0)} loc)" + (f"  used by: {', '.join(users)}" if users else ""))
            if f in inv.py:
                out += file_outline(root, f)[:max_lines]
    return "\n".join(out)
