LIST_LIMITS = {"model_tests": 3, "test_files": 5, "code_files": 8}

def _architecture(data: dict, graph: dict[str, set[str]]):
    """Only cheap cycle/layer/duplicate-owner rules; share full debt normalization with lint."""
    findings, by_component = structural_findings(data, graph) + duplicate_owner_findings(data), defaultdict(list)
    for finding in findings:
        if finding.code == "duplicate_owner":
            members = re.findall(r"'([^']+)'", finding.message.rpartition("is claimed by")[2]) or [finding.component]
        else:
            members = finding.message.split(";", 1)[0].split(" <-> ") if finding.code == "dependency_cycle" else [finding.component]
        for cid in members:
            by_component[cid].append(finding)
    findings, used = apply_accepted_debts(findings, normalized_debts(data))
    return findings, used, by_component

def _capped(items, limit: int) -> str:
    """One shared list cap: ``a, b, c +N more``."""
    items = list(items)
    shown = ", ".join(items[:limit])
    return shown + (f" +{len(items) - limit} more" if len(items) > limit else "")

def _shown_lists(facets) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Displayed code/tests items: every list-like facet is capped, even within budget."""
    code = []
    for item in facets.code:
        if item.startswith("files: "):
            item = "files: " + _capped(item[len("files: "):].split(", "), LIST_LIMITS["code_files"])
        code.append(item)
    tests, bindings = [], []
    for item in facets.tests:
        head, separator, rest = item.partition(" files: ")
        if separator and head.isdigit() and rest != "-":
            item = f"{head} files: " + _capped(rest.split(", "), LIST_LIMITS["test_files"])
        if " -> " in item and facets.rules_source != "map":
            bindings.append(item)
            continue
        tests.append(item)
    limit = LIST_LIMITS["model_tests"]
    shown = bindings[:limit] + ([f"+{len(bindings) - limit} more"] if len(bindings) > limit else [])
    return tuple(code), tuple(shown + tests)

def _unreadable(facets) -> str:
    return f"not readable statically; python -m flowguard map models {facets.model_id or '<id>'} prints them"

def _rule_text(facets) -> str:
    if facets.rules_source == "map":
        return "; ".join(facets.rules) or "-"
    if facets.rules_source == "runtime":
        return _unreadable(facets)
    if facets.rules_source == "file":
        return ", ".join(facets.rules) + " (found in the file; map models prints the real ones)"
    notes = facets.rule_notes or ("",) * len(facets.rules)
    text = "; ".join(name + (": " + (note[:69] + "…" if len(note) > 70 else note) if note else "")
                     for name, note in zip(facets.rules, notes)) or "-"
    if facets.cases is not None:
        defects, benign = facets.cases
        text += (f"; cases: {len(defects)} defects ({_capped(defects, 6)})"
                 + (f", {len(benign)} benign ({_capped(benign, 6)})" if benign else ", 0 benign"))
    return text

def _facet_lines(facets, indent: str) -> list[str]:
    rules = _rule_text(facets)
    bad = ", ".join(facets.known_bad) or (_unreadable(facets) if facets.known_bad_count is None else "-")
    if facets.known_bad_source == "system-root":
        bad = str(facets.known_bad_count)
    if facets.known_bad_source in {"system", "system-root"}:
        bad += " (generated by the system model)"
    code, tests = _shown_lists(facets)
    return [indent + label + ": " + text for label, text in (
        ("purpose", facets.purpose), ("rules", rules), ("known-bad", bad),
        ("code", "; ".join(code) or "-"), ("tests", "; ".join(tests) or "-"))]

def _count(value):
    return "?" if value is None else str(value)

def _descendant_tests(tree, mid, facets) -> tuple[int, list[str]]:
    """Bindings of every model below ``mid``: a parent shows the tests its children bind."""
    total, names, pending = 0, [], list(tree.children(mid, "model"))
    while pending:
        child = pending.pop(0)
        if child.id in facets:
            total += facets[child.id].test_count
            if facets[child.id].test_count:
                names.append(child.id)
        pending.extend(tree.children(child.id, "model"))
    return total, sorted(names)

def _model_lines(tree, ids: set[str], facets, *, component: str | None = None, bindings: bool = False,
                 changes=None, previous=None, relation=None) -> list[str]:
    roots = sorted((tree.nodes[mid] for mid in ids if tree.nodes[mid].parent_kind != "model"
                    or tree.nodes[mid].parent not in ids), key=lambda n: n.id)
    pending, lines = [(node, 1) for node in reversed(roots)], []
    while pending:
        node, depth = pending.pop()
        fact = facets[node.id]
        purpose = fact.purpose[:50] + ("…" if len(fact.purpose) > 50 else "")
        home = f" (home {node.home})" if component and (node.home_kind != "component" or node.home != component) else ""
        mark = changes.get(("model", node.id), "") if changes is not None else ""
        prefix = mark + " " if mark else ""
        rolled, child_ids = _descendant_tests(tree, node.id, facets)
        more = f" +{rolled} in children" if rolled else ""
        kind = next((kind for parent, child, kind in relation.composition if child == node.id), '') if relation else ''
        relation_label = f' [{kind} of {node.parent}]' if kind else ''
        lines.append("  " * depth + prefix + f"model {node.id}: {purpose} "
                     f"({fact.rule_count_text} rules, {_count(fact.known_bad_count)} known-bad, {fact.test_count} tests{more}){relation_label}{home}")
        if relation:
            consumed = [f'{producer}.{key} -> {into if into is not None else "(atoms)"}'
                        for producer, consumer, key, into in relation.consumption if consumer == node.id]
            if consumed:
                lines.append('  '*(depth+1)+'consumes: '+', '.join(consumed[:6])+(f', +{len(consumed)-6}' if len(consumed)>6 else ''))
        if component:
            lines.append("  " * (depth + 1) + model_port_line(node, tree, limit=max(0, 200-2*(depth+1))))
        start = len(lines)
        before = previous.get(("model", node.id)) if previous is not None else None
        if mark == "-":
            lines[-1] += " (removed by the target)"
        elif changes is not None and bindings:
            lines.extend(_facet_lines_with_was(fact, before[1] if before else None, "  " * (depth + 1)))
        elif bindings:
            lines.extend(_facet_lines(fact, "  " * (depth + 1)))
        elif changes is not None and mark:
            delta = _node_delta("model", before, (node, fact))
            if delta:
                lines.append("  " * (depth + 1) + "changes: " + "; ".join(delta))
        if rolled:
            for index in range(start, len(lines)):
                if lines[index].lstrip().startswith("tests: "):
                    lines[index] += f"; children: {rolled} tests in {', '.join(child_ids)}"
        pending.extend((child, depth + 1) for child in reversed(tree.children(node.id, "model")) if child.id in ids)
    return lines

def _facet_lines_with_was(fact, before, indent):
    lines, old = [], _facet_lines(before, "") if before is not None else []
    for index, line in enumerate(_facet_lines(fact, "")):
        lines.append(indent + line)
        if old and line != old[index]:
            lines.append(indent + "was: " + old[index].partition(": ")[2])
    return lines

def _node_fields(kind, record):
    node, fact = record
    # Only written facts: computed coverage, STALE and computed test counts are not changes.
    fields = {"purpose": (fact.purpose,), "rules": fact.rules or (("not readable statically",) if fact.rule_count is None else ()),
              "known-bad": fact.known_bad or (("not readable statically",) if fact.known_bad_count is None else ()),
              "code": tuple(value for value in fact.code if value != "STALE" and not value.startswith("coverage: ")
                            and not re.fullmatch(r"\d+ files/\d+ loc", value)),
              "tests": tuple(value for value in fact.tests if " -> " in value
                             and not value.startswith(("unbound: ", "bindable: ")))}
    if kind == "component":
        fields["code"] = tuple(value for value in fields["code"]
                               if not value.startswith(("entry: ", "state: ", "effects: "))) + tuple(node.get("entrypoints", []))
        fields["state"] = tuple(node.get("state", []))
        fields["effects"] = tuple(node.get("side_effects", []))
        fields["parent"] = (f"component {node['parent']}" if node.get("parent") else "system",)
        for field, label in (("files", "files"), ("depends_on", "uses"), ("tests", "tests"), ("layer", "layer")):
            value = node.get(field, []) if field != "layer" else (node.get(field) or "unlayered",)
            fields[label] = tuple(dict.fromkeys((*fields.get(label, ()), *value)))
    elif kind == "model":
        fields["parent"] = ("system" if node.parent_kind == "system" else f"{node.parent_kind} {node.parent}",)
        fields["file"] = (node.path,)
    return fields

def _node_delta(kind, before, after):
    old = _node_fields(kind, before) if before else {}
    new = _node_fields(kind, after) if after else {}
    parts = []
    for label in dict.fromkeys([*new, *old]):
        for sign, values, other in (("+", new.get(label, ()), old.get(label, ())),
                                    ("-", old.get(label, ()), new.get(label, ()))):
            for value in values:
                if value not in other:
                    shown_label, shown_value = label, value
                    if label == "code" and value.startswith("state: "):
                        shown_label, shown_value = "state", value[7:]
                    parts.append(f"{shown_label} {sign} {shown_value}")
    return parts

def _dependency_symbols(data, inv, cid, dep, raw):
    components = {component["id"]: component for component in data["components"]}
    sources = set(component_files(component_scope(data, components[cid]), inv))
    destinations = set(component_files(component_scope(data, components[dep]), inv))
    symbols = {target.partition("#")[2] for source, targets in raw["edges"].items()
               if source.partition("#")[0] in sources for target in targets
               if target.partition("#")[0] in destinations}
    modules = {info.module: path for path, info in inv.py.items()}
    for path in sources:
        if path not in inv.py:
            continue
        for imported in inv.py[path].imports:
            module, separator, name = imported.partition(":")
            if separator and name != "*" and resolve_import(imported, modules, importer=path, py_paths=inv.py, import_roots=inv.import_roots) in destinations:
                symbols.add(name)
    return sorted(symbols)

def _dependency_lines(data, inv, cid, graph, raw):
    lines = []
    members = {comp["id"] for comp in component_subtree(data, cid)}
    dependencies = {dep for member in members for dep in graph.get(member, ())}
    for dep in sorted(dependencies):
        symbols = _dependency_symbols(data, inv, cid, dep, raw)
        symbols = [symbol + (" (private)" if private_name(symbol.rsplit(".", 1)[-1]) else "") for symbol in symbols]
        shown = ", ".join(symbols[:6]) if symbols else "(module import only)"
        if len(symbols) > 6:
            shown += f" (+{len(symbols) - 6} more)"
        lines.append(f"  uses {dep}: {shown}")
    return lines

def _layer_order(data: dict, identities: set[str]) -> list[tuple[dict, int]]:
    """View order: top-level components top-down by layer (unlayered last), map order inside one
    layer; children stay right under their parent (a child shares its parent's layer)."""
    layers = {layer: index for index, layer in enumerate(data.get("layers", []))}
    ranked = sorted(data["components"], key=lambda c: layers.get(c.get("layer"), len(layers)))
    return component_order({**data, "components": ranked}, identities)

def _component_block(lines, depth):
    return "\n".join(("  " * depth + line) if line else line for line in "\n".join(lines).split("\n"))

def _tidy(text: str) -> str:
    """At most one blank line between blocks."""
    return re.sub(r"\n{3,}", "\n\n", text)

def _shorten(line: str, width: int) -> str:
    return line if len(line) <= width else line[:max(0, width - 1)] + "…"

def _bounded_focus(*args):
    return _tidy(_bounded_focus_raw(*args))

def _bounded_focus_raw(top, focus, full, compact, children, compact_children, must, budget):
    """read --component X: shorten inside X's block, never hide X itself.

    Order: capped lists (always), model facets reduced to model headings, child
    component blocks hidden and named, then X's own lines shortened with "…".
    """
    text = top + "\n" + "\n".join([full, *(block for _, block in children)])
    if len(text) <= budget:
        return text
    suggested = -(-len(text) // 1000) * 1000

    def notice(hidden):
        names = f"not shown: {', '.join(hidden)}; " if hidden else ""
        return (f"\n... shortened to fit {budget} chars; {names}"
                f"python -m flowguard read --component {focus} --budget {suggested} shows all")

    text = top + "\n" + "\n".join([compact, *(block for _, block in compact_children)])
    if len(text) + len(notice([])) <= budget:
        return text + notice([])
    names = [cid for cid, _ in compact_children]
    shown, hidden = top + "\n" + compact, []
    for cid, block in compact_children:
        if not hidden and len(shown) + 1 + len(block) + len(notice(names[names.index(cid) + 1:])) <= budget:
            shown += "\n" + block
        else:
            hidden.append(cid)
    if len(shown) + len(notice(hidden)) <= budget:
        return shown + notice(hidden)
    # Keep X's heading and its five facet lines; shorten each line until all fit.
    note = notice(names)
    if len(note) > budget // 3:
        note = f"\n... shortened to fit {budget} chars"
    available = budget - len(note)
    minimum = [min(len(line), (line.index("]") + 3) if line.startswith("## ") and "]" in line
                   else len(line.partition(": ")[0]) + 3) for line in must]
    # The requested block outranks the overview lines above it at this point.
    room = available - 1 - (len(must) - 1)
    width = max((len(line) for line in must), default=0)
    while width > 1 and sum(max(low, min(len(line), width)) for line, low in zip(must, minimum)) > room:
        width -= 1
    lines = [_shorten(line, max(low, width)) for line, low in zip(must, minimum)]
    return ("\n" + "\n".join(lines) + note)[:budget]

def _bounded_show(top, essential, blocks, budget):
    return _tidy(_bounded_show_raw(_tidy(top), essential, [(cid, _tidy(block)) for cid, block in blocks], budget))

def _bounded_show_raw(top, essential, blocks, budget):
    text = top + "\n" + "\n".join(b for _, b in blocks)
    if len(text) <= budget:
        return text
    reserve = min(160, max(len("\n... truncated"), budget // 2))
    shown = ""
    rows = top.splitlines()
    if len(essential) > budget - reserve:
        rows = rows[:1] + [line for line in rows[1:] if line.startswith("> flow ")] + [line for line in rows[1:] if not line.startswith("> flow ")]
    for line in rows:
        candidate = shown + ("\n" if shown else "") + line
        if len(candidate) > budget - reserve:
            break
        shown = candidate
    hidden: list[str] = []
    for cid, block in blocks:
        if not hidden and len(shown) + 1 + len(block) <= budget - reserve:
            shown += "\n" + block
        else:
            hidden.append(cid)
    named = []
    for cid in hidden:
        if len(", ".join(named + [cid])) > reserve - 90:
            break
        named.append(cid)
    names = ", ".join(named) + (f" +{len(hidden) - len(named)} more" if len(named) < len(hidden) else "")
    notice = f"\n... truncated at {budget} chars; not shown: {names}; use read --component ID"
    if len(shown) + len(notice) > budget:
        notice = f"\ntruncated; not shown: {len(hidden)}"
    return (shown + notice)[:budget]
